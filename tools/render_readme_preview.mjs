// Reproducible public synthetic artwork. No device, network, GPX or OSM input.
// CC700_BROWSER=/path/to/chrome-headless-shell node tools/render_readme_preview.mjs
// Requires @napi-rs/canvas in .local/render-check/node_modules (or CC700_CANVAS).
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { buildRoute } from '../js/route.js';
import { readFile, draw, rgb565 } from '../js/preview.js';
import { previewGuidance } from '../js/preview_guidance.js';
import { nameImage } from '../js/names.js';
const require = createRequire(import.meta.url);
const { createCanvas } = require(path.resolve(process.env.CC700_CANVAS || '.local/render-check/node_modules/@napi-rs/canvas'));
globalThis.document = { createElement(tag) {
  if (tag !== 'canvas') throw Error('Only canvas is needed for actual name bitmap generation');
  return createCanvas(1,1);
} };
const browser = process.env.CC700_BROWSER;
if (!browser) throw Error('Set CC700_BROWSER to a Chromium-compatible headless browser executable');
const output = path.resolve('docs/comparison');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'cc700-readme-'));
const source = fs.readFileSync('index.html', 'utf8');
const css = source.match(/<style>([\s\S]*?)<\/style>/)[1];
const display = source.slice(source.indexOf('      <div class="device-screen">'), source.indexOf('      <div class="playback">'));
const at = ([e,n]) => [51 + n / 111320, 7 + e / (111320 * Math.cos(51 * Math.PI / 180)), 0];
const xy = [[0,-800],[0,0],[22,0],[22,350],[-220,350],[-220,600]];
const sampled = [];
for (let i=1;i<xy.length;i++) {
  const [a,b]=[xy[i-1],xy[i]], count=Math.ceil(Math.hypot(b[0]-a[0],b[1]-a[1])/10);
  for(let j=0;j<count;j++) sampled.push(at([a[0]+(b[0]-a[0])*j/count,a[1]+(b[1]-a[1])*j/count]));
}
sampled.push(at(xy.at(-1)));
const road = (name,kind,points) => ({name,kind,pts:points.map(at)});
const roads = [road('River Road',1,[[0,-1000],[0,180]]),road('Quill Alley',2,[[-140,0],[180,0]]),
  road('Park Lane',2,[[22,-120],[22,350]]),road('Market Way',1,[[-400,350],[240,350]]),
  road('Canal Way',2,[[-220,200],[-220,700]]),road('East Street',2,[[130,-800],[130,500]]),
  ...[-650,-500,-350,-200].map(n=>road('Side street',2,[[-130,n],[170,n]]))];
const polygon=(a,b,c,d)=>[[at(a),at(b),at(c),at(d),at(a)]];
const water=[polygon([220,-1000],[500,-1000],[500,800],[220,800])];
const green=[polygon([-180,80],[5,80],[5,290],[-180,290])];
const make = styled => buildRoute({name:'SYNTHETIC reference layout',pts:sampled},roads,
  {id:'SYNTHETIC',nameImage,water,green,map:{styled,names:false}});
const stock=make(false),sunlight=make(true);
const modelStock=readFile(stock.file),modelSunlight=readFile(sunlight.file);
// OnelapFit comparison is intentionally a small-spoke reconstruction. It is
// not generated by OnelapFit and does not use its proprietary renderer/data.
const schematic={...modelStock,blocks:modelStock.blocks.map(block=>block.map(entry=>{
  if(entry.style) return entry;
  return {...entry,points:entry.points.map(p=>{
    const dy=(p[0]-entry.center[0])*111320,dx=(p[1]-entry.center[1])*111320*Math.cos(51*Math.PI/180);
    const ratio=Math.min(1,22/Math.hypot(dx,dy));
    return [entry.center[0]+(p[0]-entry.center[0])*ratio,entry.center[1]+(p[1]-entry.center[1])*ratio];
  })};
}))};
const modes=[['OnelapFit-style schematic','Reconstruction · synthetic route',stock,schematic,false],
 ['CC700 Map · Original','Generated route file · synthetic',stock,modelStock,false],
 ['CC700 Map · Sunlight v21','Generated route file · synthetic',sunlight,modelSunlight,true]];
function renderPanel(mode,distance) {
  const [title,subtitle,built,model,styled]=mode;
  const canvas=createCanvas(240,256),ctx=canvas.getContext('2d');
  if(model===schematic) {
    const nativeStroke=ctx.stroke.bind(ctx);
    ctx.stroke=function(){
      const width=this.lineWidth;
      if(this.strokeStyle===rgb565('#c8d0de')&&width===8)this.lineWidth=3;
      if(this.strokeStyle===rgb565('#ffffff')&&width===4)this.lineWidth=1;
      nativeStroke(); this.lineWidth=width;
    };
  }
  const {heading}=draw(canvas,model,distance,styled,{profile:'v21'});
  const state=previewGuidance(built.sections,distance,built.distance);
  const set=(html,id,value)=>html.replace(new RegExp(`(<(?:span|small|div|strong|dd)[^>]*id="${id}"[^>]*>)[^<]*`),`$1${value}`);
  let html=display.replace('<canvas id="cv"','<canvas data-map="'+canvas.toDataURL('image/png')+'" id="cv"');
  const inKm=state.remaining>=1000;
  const values={turnDistance:inKm?(state.remaining/1000).toFixed(1):Math.round(state.remaining),turnUnit:inKm?'km':'m',
    turnCaption:state.caption,rideSpeed:'12.9',rideHeading:['N','NE','E','SE','S','SW','W','NW'][Math.round(heading/45)%8],
    rideRemaining:((built.distance-distance)/1000).toFixed(2)};
  for(const [id,value]of Object.entries(values))html=set(html,id,value);
  html=html.replace('data-dir="0"',`data-dir="${state.dir}"`)
    .replace('id="rideCompass"',`id="rideCompass" style="transform:rotate(${-heading}deg)"`)
    .replace('class="ride-track"',`class="ride-track" style="--ride-progress:${distance/built.distance*100}%"`)
    .replace('id="rideProgress"',`id="rideProgress" style="transform:scaleX(${distance/built.distance})"`);
  return `<article><h2>${title}</h2><p>${subtitle}</p>${html}</article>`;
}
function frame(distance,index) {
  const html=`<!doctype html><meta charset="utf-8"><style>${css}
    body{background:#fff;color:#16212c;width:840px;height:426px;overflow:hidden}
    .panels{display:grid;grid-template-columns:repeat(3,252px);gap:24px;padding:12px 18px}
    article{width:252px}article h2{font-size:15px;line-height:20px;margin:0;text-align:center}
    article>p{font-size:10px;line-height:14px;margin:2px 0 0;text-align:center;color:#455564}
    .device-screen{width:252px;margin-top:8px}
    footer{position:absolute;left:18px;bottom:4px;font-size:10px;color:#455564}
  </style><div class="panels">${modes.map(m=>renderPanel(m,distance)).join('')}</div>
  <footer>240 × 320 display · Two-row native card structure · Fonts, raster and chevron spacing approximate · No real ride coordinates</footer>
  <script>Promise.all([...document.querySelectorAll('canvas')].map(c=>new Promise(resolve=>{const i=new Image();i.onload=()=>{c.getContext('2d').drawImage(i,0,0);resolve()};i.src=c.dataset.map}))).then(()=>document.documentElement.dataset.ready='true')</script>`;
  const file=path.join(temporary,`frame-${index}.html`),png=path.join(temporary,`frame-${String(index).padStart(3,'0')}.png`);
  fs.writeFileSync(file,html);
  execFileSync(browser,['--headless','--no-sandbox','--disable-gpu','--hide-scrollbars',
    '--no-first-run','--disable-background-networking','--virtual-time-budget=1000',
    '--window-size=840,426',`--screenshot=${png}`,pathToFileURL(file).href],{timeout:30000,stdio:'pipe'});
  return png;
}
try {
  const scenes=[['far-straight',134],['approaching-turn',500],['near-turn',650],['close-pair',728],['second-turn',810],['park-street',930]];
  for(const [i,[name,distance]]of scenes.entries()){
    fs.copyFileSync(frame(distance,i),path.join(output,`synthetic-${name}-current-ui.png`));
  }
  // 13 on-route positions, 1.5 seconds each. Motion is position replay rather
  // than elapsed-time/GPS simulation; all three panels share the same distance.
  for(let i=0;i<13;i++)frame(650+i*15,i);
  execFileSync('img2webp',['-loop','0','-lossless','-d','1500',
    ...Array.from({length:13},(_,i)=>path.join(temporary,`frame-${String(i).padStart(3,'0')}.png`)),
    '-o',path.join(output,'synthetic-current-ui-replay.webp')],{stdio:'pipe'});
  console.log('Rendered six synthetic current-UI comparisons and 13-frame WebP replay');
} finally {fs.rmSync(temporary,{recursive:true,force:true})}
