// OnelapFit comparison is intentionally a reconstruction; it is not generated by
// OnelapFit and does not use its proprietary renderer/data. The original formulates
// junction marks only where a road crosses the route: every crossing road is drawn
// as a uniform ~200 m stub (±100 m each side of the crossing), the same size for
// every road class. No class-based width or length, no junction without a crossing.
const schematic = (() => {
  const R = gpx.pts, kx = Math.cos(51 * Math.PI / 180) * 111320, ky = 111320;
  const m = p => [p[1] * kx, p[0] * ky];
  const Rm = R.map(m);
  const routeDist = [0];
  for (let i = 1; i < R.length; i++) routeDist.push(routeDist[i - 1] + Math.hypot(Rm[i][0] - Rm[i - 1][0], Rm[i][1] - Rm[i - 1][1]));
  const total = routeDist.at(-1);
  const sectionsOf = modelPlain.secs, secStart = sectionsOf.map(s => s[0]?.[2] ?? 0);
  const blocks = modelPlain.blocks.map(b => b.filter(e => false));  // empty per-section arrays
  const ARM = 100;
  const cross = (p1, p2, p3, p4) => {                       // intersection point in metres or null
    const d = (p2[0] - p1[0]) * (p4[1] - p3[1]) - (p2[1] - p1[1]) * (p4[0] - p3[0]);
    if (!d) return null;
    const t = ((p3[0] - p1[0]) * (p4[1] - p3[1]) - (p3[1] - p1[1]) * (p4[0] - p3[0])) / d;
    const u = ((p3[0] - p1[0]) * (p2[1] - p1[1]) - (p3[1] - p1[1]) * (p2[0] - p1[0])) / d;
    return t > 0.002 && t < 0.998 && u > 0.002 && u < 0.998 ? [p1[0] + t * (p2[0] - p1[0]), p1[1] + t * (p2[1] - p1[1])] : null;
  };
  const angleBetween = (a, b) => Math.abs(Math.atan2(Math.sin(a - b), Math.cos(a - b)));
  let crossings = 0;
  for (const { pts } of osm.lines) {
    const W = pts.map(m);
    for (let i = 1; i < W.length; i++) {
      for (let j = 1; j < Rm.length; j++) {
        const p = cross(W[i - 1], W[i], Rm[j - 1], Rm[j]);
        if (!p) continue;
        const wayA = Math.atan2(W[i][1] - W[i - 1][1], W[i][0] - W[i - 1][0]);
        const routeA = Math.atan2(Rm[j][1] - Rm[j - 1][1], Rm[j][0] - Rm[j - 1][0]);
        if (angleBetween(wayA, routeA) < 0.6) continue;     // the route's own road: no stub
        // walk ±ARM metres along the way from the crossing
        const arms = [];
        for (const dir of [-1, 1]) {
          let remain = ARM, x = p[0], y = p[1], k = i;
          while (remain > 0) {
            const n = k + (dir < 0 ? 0 : 1), q = W[dir < 0 ? k - 1 : k];
            if (!q) break;
            const d = Math.hypot(q[0] - x, q[1] - y);
            if (d >= remain) { x += (q[0] - x) / d * remain; y += (q[1] - y) / d * remain; remain = 0; }
            else { x = q[0]; y = q[1]; remain -= d; k += dir; }
          }
          arms.push([y / ky, x / kx]);
        }
        // block/section of the crossing by route distance
        const rd = routeDist[j - 1] + Math.hypot(p[0] - Rm[j - 1][0], p[1] - Rm[j - 1][1]);
        let sec = 0;
        for (let s = secStart.length - 1; s >= 0; s--) if (rd * 100 >= secStart[s]) { sec = s; break; }
        if (blocks[sec]) blocks[sec].push({ style: 0, center: [p[1] / ky, p[0] / kx], points: arms });
        crossings++;
        break;                                              // one stub per way crossing this route segment
      }
    }
  }
  console.log(`OnelapFit-style reconstruction: ${crossings} uniform crossing stubs on ${total.toFixed(0)} m`);
  return { ...modelPlain, blocks };
})();

const sampleAt = (all, distM) => {
  const d = distM * 100;
  for (let i = 1; i < all.length; i++) {
    if (all[i][2] >= d || i === all.length - 1) {
      const a = all[i - 1], b = all[i], span = (b[2] - a[2]) || 1, t = Math.max(0, Math.min(1, (d - a[2]) / span));
      return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
    }
  }
  return all[0];
};

// Simplified OpenStreetMap-standard colours over the same cached data, same viewpoint.
function osmMap(distance) {
  const canvas = createCanvas(240, 256), g = canvas.getContext('2d');
  const all = modelSunlight.secs.flat();
  const me = sampleAt(all, distance);
  const heading = brg(sampleAt(all, distance - 30), sampleAt(all, distance + 30));
  const sin = Math.sin(heading * Math.PI / 180), cos = Math.cos(heading * Math.PI / 180), k = Math.cos(me[0] * Math.PI / 180);
  const project = p => {
    const e = (p[1] - me[1]) * 111320 * k / 2.5, n = (p[0] - me[0]) * 111320 / 2.5;
    return [Math.trunc(120 + e * cos - n * sin), Math.trunc(256 * 0.85 - e * sin - n * cos)];
  };
  const poly = ring => { g.beginPath(); ring.map(project).forEach(([x, y], i) => i ? g.lineTo(x, y) : g.moveTo(x, y)); g.closePath(); };
  const line = (pts, color, width, dash = []) => {
    const pp = pts.map(project); if (pp.length < 2) return;
    g.strokeStyle = color; g.lineWidth = width; g.setLineDash(dash); g.lineCap = width >= 3 ? 'round' : 'butt';
    g.beginPath(); pp.forEach(([x, y], i) => i ? g.lineTo(x, y) : g.moveTo(x, y)); g.stroke(); g.setLineDash([]);
  };
  g.fillStyle = '#f2efe9'; g.fillRect(0, 0, 240, 256);
  for (const rings of osm.areas) { g.fillStyle = '#e0dfda'; poly(rings[0]); g.fill(); }
  for (const rings of osm.green) { g.fillStyle = '#add19e'; poly(rings[0]); g.fill(); }
  for (const rings of osm.water) { g.fillStyle = '#aad3df'; poly(rings[0]); g.fill(); g.strokeStyle = '#7fa8cf'; g.lineWidth = 1.5; g.stroke(); }
  for (const pts of osm.wlines ?? []) line(pts, '#7fa8cf', 2);
  for (const pts of osm.rails ?? []) line(pts, '#9b9b9b', 1.5, [5, 4]);
  const CASING = { 8: ['#dc2a67', 6.5], 1: ['#d19b5f', 6.5], 2: ['#cfc9c1', 5], 3: ['#cfc9c1', 4.5], 4: ['#cfc9c1', 3] };
  const FILL = { 8: ['#e892a2', 5], 1: ['#fcd6a4', 5], 2: ['#ffffff', 3.5], 3: ['#ffffff', 3], 4: ['#ffffff', 2] };
  for (const pass of [CASING, FILL]) for (const { kind, pts } of osm.lines) {
    if (!pass[kind & 0x7f]) continue;
    line(pts, pass[kind & 0x7f][0], pass[kind & 0x7f][1]);
  }
  for (const { kind, pts } of osm.lines) {
    const k = kind & 0x7f;
    if (k === 5 || k === 6) line(pts, '#c08050', 1.5, [4, 3]);
    else if (k === 7) line(pts, '#d9cfc0', 1);
  }
  const route = all.map(p => [p[0], p[1]]);
  line(route.slice(0, Math.max(2, route.length)), '#ffffff', 6);
  line(route, '#1f6fe0', 4);
  const [x, y] = project(me);
  g.beginPath(); g.arc(x, y, 17, 0, Math.PI * 2); g.fillStyle = '#fbfdff'; g.fill();
  g.strokeStyle = '#9ac6f5'; g.lineWidth = 2; g.stroke();
  return canvas.toDataURL('image/png');
}

const modes = [['OnelapFit original · schematic', 'Reconstruction · Tour D3 · unpatched look', plain, schematic, false],
  ['CC700 Map · Junction + areas', 'Software original · grey built-up, water, rail', junction, modelJunction, false],
  ['CC700 Map · Sunlight v21', 'Full map solution · patched firmware', sunlight, modelSunlight, true]];
function renderPanel(mode, distance) {
  const [title, subtitle, built, model, styled] = mode;
  const canvas = createCanvas(240, 256), ctx = canvas.getContext('2d');
  if (model === schematic) {
    const nativeStroke = ctx.stroke.bind(ctx);
    ctx.stroke = function () {
      const width = this.lineWidth;
      if (this.strokeStyle === rgb565('#c8d0de') && width === 8) this.lineWidth = 5;
      if (this.strokeStyle === rgb565('#ffffff') && width === 4) this.lineWidth = 2;
      nativeStroke(); this.lineWidth = width;
    };
  }
  const { heading } = draw(canvas, model, distance, styled, { profile: 'v21' });
  const state = previewGuidance(built.sections, distance, built.distance);
  const set = (html, id, value) => html.replace(new RegExp(`(<(?:span|small|div|strong|dd)[^>]*id="${id}"[^>]*>)[^<]*`), `$1${value}`);
  let html = display.replace('<canvas id="cv"', `<canvas data-map="${canvas.toDataURL('image/png')}" id="cv"`);
  const inKm = state.remaining >= 1000;
  const values = { turnDistance: inKm ? (state.remaining / 1000).toFixed(1) : Math.round(state.remaining), turnUnit: inKm ? 'km' : 'm',
    turnCaption: state.caption, rideSpeed: '12.9', rideHeading: ['N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW'][Math.round(heading / 45) % 8],
    rideRemaining: ((built.distance - distance) / 1000).toFixed(2) };
  for (const [id, value] of Object.entries(values)) html = set(html, id, value);
  html = html.replace('data-dir="0"', `data-dir="${state.dir}"`)
    .replace('id="rideCompass"', `id="rideCompass" style="transform:rotate(${-heading}deg)"`)
    .replace('class="ride-track"', `class="ride-track" style="--ride-progress:${distance / built.distance * 100}%"`)
    .replace('id="rideProgress"', `id="rideProgress" style="transform:scaleX(${distance / built.distance})"`);
  return `<article><h2>${title}</h2><p>${subtitle}</p>${html}</article>`;
}
function osmPanel(distance) {
  let html = display.replace('<canvas id="cv"', `<canvas data-map="${osmMap(distance)}" id="cv"`);
  return `<article><h2>OpenStreetMap · reference</h2><p>Simplified standard colours · same data</p>${html}</article>`;
}
function frame(distance, index) {
  const html = `<!doctype html><meta charset="utf-8"><style>${css}
    body{background:#fff;color:#16212c;width:1116px;height:426px;overflow:hidden}
    .panels{display:grid;grid-template-columns:repeat(4,252px);gap:24px;padding:12px 18px}
    article{width:252px}article h2{font-size:15px;line-height:20px;margin:0;text-align:center}
    article>p{font-size:10px;line-height:14px;margin:2px 0 0;text-align:center;color:#455564}
    .device-screen{width:252px;margin-top:8px}
    footer{position:absolute;left:18px;bottom:4px;font-size:10px;color:#455564}
  </style><div class="panels">${modes.map(m => renderPanel(m, distance)).join('')}${osmPanel(distance)}</div>
  <footer>Public Düsseldorf Tour D3 river section · 240 × 320 display · Map data © OpenStreetMap contributors · No private ride data</footer>
  <script>Promise.all([...document.querySelectorAll('canvas')].map(c=>new Promise(resolve=>{const i=new Image();i.onload=()=>{c.getContext('2d').drawImage(i,0,0);resolve()};i.src=c.dataset.map}))).then(()=>document.documentElement.dataset.ready='true')</script>`;
  const file = path.join(temporary, `frame-${index}.html`), png = path.join(temporary, `frame-${String(index).padStart(3, '0')}.png`);
  fs.writeFileSync(file, html);
  execFileSync(browser, ['--headless', '--no-sandbox', '--disable-gpu', '--hide-scrollbars',
    '--no-first-run', '--disable-background-networking', '--virtual-time-budget=1000',
    '--window-size=1116,426', `--screenshot=${png}`, pathToFileURL(file).href], { timeout: 30000, stdio: 'pipe' });
  return png;
}
