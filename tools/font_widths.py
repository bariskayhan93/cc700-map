#!/usr/bin/env python3
"""Glyph widths of the two stock map fonts (design 5, plan Task 4) from the C4 base: prints firmware/elev/elev_font.h.
Font 0x3c2a54d8 (the distance number, line 20) and 0x3c29188c (unit and climb, line 18). lv_font_t: dsc at +16.
The font dsc: glyph_bitmap, glyph_dsc, cmaps (one cmap). cmap: u32 range_start 32, range_length 95, glyph_id_start 1.
glyph_dsc entries are 16 B: u32 bitmap_index, u32 adv_w (1/16 px), u16 box_w, u16 box_h, i16 ofs_x, i16 ofs_y.
Width px = (adv_w + 8) >> 4. Run: python3 tools/font_widths.py > firmware/elev/elev_font.h"""
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import cc26_build as c26  # noqa: E402

FONTS = (('big', 0x3c2a54d8), ('small', 0x3c29188c))
CHARS = '0123456789.+ km'


def widths(base_bytes):
    _, segs, _ = c26.esp_module().read(base_bytes)
    u32 = lambda a: struct.unpack('<I', c26.read_any(segs, a, 4))[0]
    out = {}
    for name, font in FONTS:
        dsc = u32(font + 16)
        glyph, cmap = u32(dsc + 4), u32(dsc + 8)
        start, length, first = u32(cmap), struct.unpack('<H', c26.read_any(segs, cmap + 4, 2))[0], u32(cmap + 8)
        if (start, length, first) != (32, 95, 1):
            raise ValueError(f'font {font:#x}: cmap {start} {length} {first}')
        out[name] = {c: (u32(glyph + 16 * (first + ord(c) - start) + 4) + 8) >> 4 for c in CHARS}
    return out


def header(w):
    """One compact function: the digits, '+' and 'k' share one width in each font (asserted)."""
    rows = []
    for name in ('big', 'small'):
        x = w[name]
        n = {x[c] for c in '0123456789+k'}
        if len(n) != 1:
            raise ValueError(f'{name}: digits, + and k differ in width: {sorted(n)}')
        rows.append((n.pop(), x['m'], x['.'], x[' ']))
    (bn, bm, bd, bs), (sn, sm, sd, ss) = rows
    return f"""/* Generated by tools/font_widths.py from the C4 base: glyph widths in px of the stock map fonts.
 * big = FW_FONT_NUM (the distance number), small = FW_FONT_UNIT (unit, climb), fw.h. Characters: 0-9 + k (one width),
 * m . space.
 * No table: no data in the second code area. */
#pragma once

static __attribute__((noinline)) int el_text_w(int big, const char *s) {{
  int w = 0, c;
  while ((c = *s++) != 0) w += c == 'm' ? (big ? {bm} : {sm}) : c == '.' ? (big ? {bd} : {sd}) : c == ' ' ? (big ? {bs} : {ss}) : (big ? {bn} : {sn});
  return w;
}}
"""


if __name__ == '__main__':
    sys.stdout.write(header(widths((ROOT / '.local/cc25/ota_1_cc25.bin').read_bytes())))
